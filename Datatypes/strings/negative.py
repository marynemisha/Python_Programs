#negative indexing
str1="python"
print(str1)                       #python
print(str1[0:])                   #python
print(str1[-1])                   #n
print(str1[-2])                   #o
print(str1[-4:-1])                #tho
print(str1[-1:-4])                #space
print(str1[-5:-1])                #ytho
