list=["Python","Java","HTML","Django","API"]
print(list)
print(list[0])                 #first element
print(list[1])                 #second element
print(list[0:4])               #first index to 4th index
print(list[:4])                #first to 4th
print(list[:])                 #returns all elements
print(list[2:])                #second index to last
print(list[-1])                #last element